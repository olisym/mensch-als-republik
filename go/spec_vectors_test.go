func hx(s string) []byte {
	var b strings.Builder
	for _, r := range s {
		if r > ' ' {
			b.WriteRune(r)
		}
	}
	return mustHex(b.String())
}

func signed(core, sig string) []byte {
	v, err := decodeCBOR(hx(core))
	if err != nil {
		panic(err)
	}
	v.m = append(v.m, cborPair{k: cborUintVal(9), v: cborBytesVal(hx(sig))})
	return encodeCBOR(v)
}

func nv3Signed() []byte {
	fields := map[uint64]cborValue{
		0: cborUintVal(1),
		1: cborBytesVal(mustHex(aliceIHex)),
		2: cborArrayVal(cborUintVal(1), cborBytesVal(mustHex(bobIHex))),
		3: cborTextVal(tv1Pred),
		5: cborBytesVal(mustHex(scopeNHex)),
		6: cborUintVal(1700000001),
		8: cborBytesVal(mustHex(aliceGenesisHex)),
		9: cborBytesVal(hx("959245d77a82c6099905ff781e61c917e7a1de4687a4bb8e84504b5191060ef9" +
			"a81203a06e71a51144a66e886db3f62ba9fcd19171adb3f25b2288c4ef9fa403")),
	}
	return encodeCBOR(cborMapUint(fields))
}

